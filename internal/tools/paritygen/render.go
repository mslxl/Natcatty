package main

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/mslxl/natcatty/internal/parity"
)

func countRows(rows []parity.Row) map[string]int {
	counts := map[string]int{}
	for _, row := range rows {
		counts[row.Status]++
	}
	return counts
}

// render produces the committed matrix.md. Rows are sorted by area and id so
// regeneration is deterministic across machines.
func render(m *parity.Matrix) []byte {
	rows := append([]parity.Row(nil), m.Rows...)
	sort.SliceStable(rows, func(i, j int) bool {
		if rows[i].Area != rows[j].Area {
			return rows[i].Area < rows[j].Area
		}
		return rows[i].ID < rows[j].ID
	})

	counts := countRows(rows)

	var b strings.Builder
	b.WriteString("# Parity Matrix\n\n")
	b.WriteString("<!-- Generated by internal/tools/paritygen from docs/parity/matrix.yaml. Do not edit. -->\n\n")
	fmt.Fprintf(&b, "Rows: %d (verified %d, implemented %d, unverified %d, excluded %d)\n\n",
		len(rows), counts["verified"], counts["implemented"], counts["unverified"], counts["excluded"])

	area := ""
	for _, row := range rows {
		if row.Area != area {
			if area != "" {
				b.WriteString("\n")
			}
			area = row.Area
			fmt.Fprintf(&b, "## %s\n\n", area)
			b.WriteString("| ID | Feature | Module | Tickets | Acceptance tests | Manual QA | Automation exception | Status | Original paths | Notes |\n")
			b.WriteString("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
			cell(row.ID),
			cell(row.Feature),
			cell(row.Module),
			cell(strings.Join(row.Tickets, ", ")),
			cell(strings.Join(row.AcceptanceTests, "<br>")),
			cell(strings.Join(row.ManualQA, "<br>")),
			cell(row.AutomationException),
			cell(row.Status),
			cell(strings.Join(row.OriginalPaths, "<br>")),
			cell(row.Notes),
		)
	}
	return []byte(b.String())
}

func cell(value string) string {
	value = strings.ReplaceAll(value, "|", `\|`)
	value = strings.ReplaceAll(value, "\n", "<br>")
	if strings.TrimSpace(value) == "" {
		return "-"
	}
	return value
}

