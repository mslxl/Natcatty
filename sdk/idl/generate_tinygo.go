package idl

import (
	"fmt"
	"go/format"
	"strings"
)

// GenerateTinyGoConstants renders the part of the TinyGo package that has no
// build constraint: wire constants, enums, records, handles, service method
// ids, typed service helpers, and the generated ABI negotiation. The host
// import bodies live in host_tinygo.go (tinygo.wasm) and host_stub.go
// (everything else), so `go build` and `go vet` can type-check the package.
func (d *Definition) GenerateTinyGoConstants() []byte {
	var out strings.Builder
	out.WriteString("// Code generated by sdk/idl/gen from sdk/idl/natcatty_v1.idl; DO NOT EDIT.\n\n")
	out.WriteString("// Package natcatty contains generated TinyGo bindings for the Natcatty\n")
	out.WriteString("// plugin ABI. Build plugins with a freestanding reactor target; the\n")
	out.WriteString("// hello-command-tinygo sample carries one in target.json. The native stub\n")
	out.WriteString("// in host_stub.go exists only so ordinary Go tooling can type-check the\n")
	out.WriteString("// package.\n")
	out.WriteString("package natcatty\n\n")
	fmt.Fprintf(&out, "const (\n\tIDLName = %q\n\tIDLVersion = %q\n", d.Name, d.Version)
	fmt.Fprintf(&out, "\t// ABIVersion is the wire ABI major these bindings speak.\n")
	fmt.Fprintf(&out, "\tABIVersion int32 = %d\n", d.ABI)
	fmt.Fprintf(&out, "\t// HostModuleName is the imported v1 host module.\n")
	fmt.Fprintf(&out, "\tHostModuleName = %q\n)\n\n", d.HostModule().Name)

	for _, enum := range d.Enums {
		fmt.Fprintf(&out, "// %s is one generated wire enum.\n", enum.Name)
		fmt.Fprintf(&out, "type %s %s\n\n", enum.Name, tinyGoTypeName(enum.Base))
		fmt.Fprintf(&out, "const (\n")
		for _, value := range enum.Values {
			fmt.Fprintf(&out, "\t%s%s %s = %d\n", enum.Name, goCamel(value.Name), enum.Name, value.Value)
		}
		fmt.Fprintf(&out, ")\n\n")
		fmt.Fprintf(&out, "// Valid reports whether v is a declared %s value.\n", enum.Name)
		fmt.Fprintf(&out, "func (v %s) Valid() bool {\n\tswitch v {\n\tcase ", enum.Name)
		for index, value := range enum.Values {
			if index > 0 {
				out.WriteString(", ")
			}
			fmt.Fprintf(&out, "%s%s", enum.Name, goCamel(value.Name))
		}
		fmt.Fprintf(&out, ":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")
	}

	for _, record := range d.Records {
		fmt.Fprintf(&out, "// %s is one generated fixed-layout record.\n", record.Name)
		fmt.Fprintf(&out, "type %s struct {\n", record.Name)
		for _, field := range record.Fields {
			fmt.Fprintf(&out, "\t%s %s\n", goCamel(field.Name), tinyGoTypeName(field.Type))
		}
		fmt.Fprintf(&out, "}\n\n")
	}

	for _, handle := range d.Handles {
		fmt.Fprintf(&out, "// %s is an opaque generation-tagged host resource.\n", handle.Name)
		fmt.Fprintf(&out, "type %s uint64\n\n", handle.Name)
		fmt.Fprintf(&out, "// Slot returns the table slot encoded in the handle.\n")
		fmt.Fprintf(&out, "func (h %s) Slot() uint32 { return uint32(h) }\n\n", handle.Name)
		fmt.Fprintf(&out, "// Generation returns the generation encoded in the handle.\n")
		fmt.Fprintf(&out, "func (h %s) Generation() uint32 { return uint32(h >> 32) }\n\n", handle.Name)
	}

	out.WriteString("// Host service names, import modules, and stable method ids.\nconst (\n")
	for _, service := range d.Services {
		camel := goCamel(service.Name)
		fmt.Fprintf(&out, "\tService%s = %q\n", camel, service.Name)
		fmt.Fprintf(&out, "\tService%sModule = %q\n", camel, service.Module())
		for _, method := range service.Methods {
			fmt.Fprintf(&out, "\tService%sMethod%s uint32 = %d\n", camel, goCamel(method.Name), method.ID)
		}
	}
	out.WriteString(")\n\n")

	out.WriteString("// ServiceReply is one host-service call result. Payload points into the\n")
	out.WriteString("// caller's response buffer and is empty unless Status is zero.\n")
	out.WriteString("type ServiceReply struct {\n\tStatus  int32\n\tPayload []byte\n}\n\n")
	out.WriteString("// ServiceResult reads the response length the host copied for the last\n")
	out.WriteString("// successful service call and truncates the buffer to it.\n")
	out.WriteString("func ServiceResult(status int32, response []byte) ServiceReply {\n")
	out.WriteString("\tif status != 0 {\n\t\treturn ServiceReply{Status: status}\n\t}\n")
	out.WriteString("\tlength := HostServiceResponseLen()\n")
	out.WriteString("\tif uint64(length) > uint64(len(response)) {\n")
	out.WriteString("\t\tlength = uint32(len(response))\n\t}\n")
	out.WriteString("\treturn ServiceReply{Status: status, Payload: response[:length]}\n}\n\n")

	for _, service := range d.Services {
		camel := goCamel(service.Name)
		for _, method := range service.Methods {
			methodCamel := goCamel(method.Name)
			wrapper := camel + methodCamel
			if wrapper == camel+"Call" {
				wrapper = camel + "CallMethod"
			}
			fmt.Fprintf(&out, "// %s calls %s.%s with the generated method id.\n", wrapper, service.Name, method.Name)
			fmt.Fprintf(&out, "func %s(request, response []byte) int32 {\n", wrapper)
			fmt.Fprintf(&out, "\treturn %sCall(Service%sMethod%s, request, response)\n}\n\n",
				camel, camel, methodCamel)
		}
	}

	out.WriteString("// Guest export wire names.\nconst (\n")
	for _, export := range d.GuestModule().Exports {
		fmt.Fprintf(&out, "\tExport%s = %q\n", goCamel(export.Name), export.Wire)
	}
	out.WriteString(")\n\n")

	fmt.Fprintf(&out, "const abiMismatchMessage = %q\n\n",
		fmt.Sprintf("plugin ABI mismatch: generated TinyGo bindings speak ABI %d", d.ABI))
	out.WriteString("// CheckABI compares the host's abi_version with the generated major. On a\n")
	out.WriteString("// mismatch it logs one error line and returns -1; on success it returns 0.\n")
	out.WriteString("func CheckABI() int32 {\n")
	out.WriteString("\tif HostABIVersion() != ABIVersion {\n")
	out.WriteString("\t\tHostLog(LogLevelError, abiMismatchMessage)\n")
	out.WriteString("\t\treturn -1\n\t}\n\treturn 0\n}\n\n")
	out.WriteString("// GuestInit is the generated natcatty_init body: it fails closed when the\n")
	out.WriteString("// host speaks another ABI major.\n")
	out.WriteString("func GuestInit() int32 { return CheckABI() }\n")
	return gofmtOrRaw(out.String())
}

// GenerateTinyGoHost renders the tinygo.wasm half of the generated package:
// one //go:wasmimport per IDL host function and service module, plus the
// byte-slice wrappers the sample and typed SDK use.
func (d *Definition) GenerateTinyGoHost() []byte {
	var out strings.Builder
	out.WriteString("// Code generated by sdk/idl/gen from sdk/idl/natcatty_v1.idl; DO NOT EDIT.\n\n")
	out.WriteString("//go:build tinygo.wasm\n\n")
	out.WriteString("package natcatty\n\n")
	out.WriteString("import \"unsafe\"\n\n")
	out.WriteString("func bytesPtr(data []byte) uint32 {\n")
	out.WriteString("\tif len(data) == 0 {\n\t\treturn 0\n\t}\n")
	out.WriteString("\treturn uint32(uintptr(unsafe.Pointer(unsafe.SliceData(data))))\n}\n\n")
	out.WriteString("func stringPtr(value string) uint32 {\n")
	out.WriteString("\tif len(value) == 0 {\n\t\treturn 0\n\t}\n")
	out.WriteString("\treturn uint32(uintptr(unsafe.Pointer(unsafe.StringData(value))))\n}\n\n")

	host := d.HostModule()
	for _, function := range host.Functions {
		fmt.Fprintf(&out, "//go:wasmimport %s %s\n", host.Name, function.Name)
		fmt.Fprintf(&out, "func rawHost%s(%s)%s\n\n", goCamel(function.Name),
			tinyGoWireParams(d, function.Params), tinyGoWireResult(d, function.Result))
	}

	for _, wrapper := range tinyGoHostWrappers(d) {
		fmt.Fprintf(&out, "%s\n", wrapper.Doc)
		fmt.Fprintf(&out, "func %s(%s)%s {\n", wrapper.Name, wrapper.Params, wrapper.Result)
		if wrapper.Body != "" {
			fmt.Fprintf(&out, "\t%s\n", wrapper.Body)
		}
		fmt.Fprintf(&out, "}\n\n")
	}

	for _, service := range d.Services {
		camel := goCamel(service.Name)
		fmt.Fprintf(&out, "//go:wasmimport %s %s\n", service.Module(), serviceCallFunction)
		fmt.Fprintf(&out, "func raw%sCall(methodID uint32, reqPtr uint32, reqLen uint32, respPtr uint32, respCap uint32) int32\n\n", camel)
		fmt.Fprintf(&out, "// %sCall invokes one %s method with opaque request and response bytes.\n", camel, service.Name)
		fmt.Fprintf(&out, "func %sCall(methodID uint32, request, response []byte) int32 {\n", camel)
		fmt.Fprintf(&out, "\treturn raw%sCall(methodID, bytesPtr(request), uint32(len(request)), bytesPtr(response), uint32(len(response)))\n}\n\n", camel)
	}
	return gofmtOrRaw(out.String())
}

// GenerateTinyGoStub renders the non-wasm half of the generated package. It
// has exactly the same public surface as host_tinygo.go and returns zero
// values, so ordinary Go builds, vet, and unit tests compile.
func (d *Definition) GenerateTinyGoStub() []byte {
	var out strings.Builder
	out.WriteString("// Code generated by sdk/idl/gen from sdk/idl/natcatty_v1.idl; DO NOT EDIT.\n\n")
	out.WriteString("//go:build !tinygo.wasm\n\n")
	out.WriteString("package natcatty\n\n")
	out.WriteString("// This file is the native type-check stub. It never runs inside a plugin:\n")
	out.WriteString("// TinyGo builds use host_tinygo.go and the real wasm imports.\n\n")
	for _, wrapper := range tinyGoHostWrappers(d) {
		fmt.Fprintf(&out, "// %s is the native stub of the generated wrapper.\n", wrapper.Name)
		fmt.Fprintf(&out, "func %s(%s)%s {\n", wrapper.Name, wrapper.Params, wrapper.Result)
		if wrapper.Stub != "" {
			fmt.Fprintf(&out, "\t%s\n", wrapper.Stub)
		}
		fmt.Fprintf(&out, "}\n\n")
	}
	for _, service := range d.Services {
		camel := goCamel(service.Name)
		fmt.Fprintf(&out, "// %sCall is the native stub of the generated %s call.\n", camel, service.Name)
		fmt.Fprintf(&out, "func %sCall(methodID uint32, request, response []byte) int32 {\n", camel)
		fmt.Fprintf(&out, "\treturn 0\n}\n\n")
	}
	return gofmtOrRaw(out.String())
}

type tinyGoWrapper struct {
	Doc    string
	Name   string
	Params string
	Result string
	Body   string
	Stub   string
}

// tinyGoHostWrappers derives one public wrapper per host import. The common
// borrowed-slice shapes get string or []byte parameters; every other function
// keeps its exact IDL scalar shape.
func tinyGoHostWrappers(d *Definition) []tinyGoWrapper {
	host := d.HostModule()
	wrappers := make([]tinyGoWrapper, 0, len(host.Functions))
	for _, function := range host.Functions {
		wrapper := tinyGoWrapper{Name: "Host" + goCamel(function.Name)}
		params, args := tinyGoScalarParams(d, function.Params)
		wrapper.Params = params
		raw := "rawHost" + goCamel(function.Name)
		if function.Result == "" {
			wrapper.Body = fmt.Sprintf("%s(%s)", raw, args)
		} else {
			wrapper.Result = " " + tinyGoWireTypeName(d, function.Result)
			wrapper.Body = fmt.Sprintf("return %s(%s)", raw, args)
			wrapper.Stub = "return 0"
		}

		switch function.Name {
		case "abi_version":
			if len(function.Params) == 0 && function.Result == "i32" {
				wrapper.Result = " int32"
				wrapper.Body = "return rawHostABIVersion()"
				wrapper.Stub = "return ABIVersion"
			}
		case "log":
			if len(function.Params) == 3 && function.Params[1].Type == "u32" &&
				function.Params[2].Type == "u32" {
				wrapper.Params = fmt.Sprintf("level %s, message string", tinyGoTypeName(function.Params[0].Type))
				wrapper.Body = fmt.Sprintf("%s(%s, stringPtr(message), uint32(len(message)))",
					raw, tinyGoArg(d, function.Params[0].Type, "level"))
				wrapper.Result = ""
				wrapper.Stub = ""
			}
		case "random_get":
			if len(function.Params) == 2 && function.Result == "i32" {
				wrapper.Params = "buffer []byte"
				wrapper.Body = fmt.Sprintf("return %s(bytesPtr(buffer), uint32(len(buffer)))", raw)
				wrapper.Result = " int32"
				wrapper.Stub = "for index := range buffer {\n\t\tbuffer[index] = 0\n\t}\n\treturn 0"
			}
		case "output_write":
			if len(function.Params) == 2 && function.Result == "i32" {
				wrapper.Params = "data []byte"
				wrapper.Body = fmt.Sprintf("return %s(bytesPtr(data), uint32(len(data)))", raw)
				wrapper.Result = " int32"
				wrapper.Stub = "return int32(len(data))"
			}
		case "language_respond", "service_respond", "provider_respond", "data_provider_respond":
			if len(function.Params) == 3 && function.Result == "i32" &&
				function.Params[1].Type == "u32" && function.Params[2].Type == "u32" {
				wrapper.Params = fmt.Sprintf("requestID %s, payload []byte",
					tinyGoTypeName(function.Params[0].Type))
				wrapper.Body = fmt.Sprintf("return %s(%s, bytesPtr(payload), uint32(len(payload)))",
					raw, tinyGoArg(d, function.Params[0].Type, "requestID"))
				wrapper.Result = " int32"
				wrapper.Stub = "return 0"
			}
		case "mcp_tool_result":
			if len(function.Params) == 3 && function.Result == "i32" {
				wrapper.Params = fmt.Sprintf("requestID %s, payload []byte",
					tinyGoTypeName(function.Params[0].Type))
				wrapper.Body = fmt.Sprintf("return %s(%s, bytesPtr(payload), uint32(len(payload)))",
					raw, tinyGoArg(d, function.Params[0].Type, "requestID"))
				wrapper.Result = " int32"
				wrapper.Stub = "return 0"
			}
		case "mcp_tool_progress":
			if len(function.Params) == 4 && function.Result == "i32" {
				wrapper.Params = "requestID uint32, progress uint32, message []byte"
				wrapper.Body = fmt.Sprintf("return %s(requestID, progress, bytesPtr(message), uint32(len(message)))", raw)
				wrapper.Result = " int32"
				wrapper.Stub = "return 0"
			}
		case "provider_input_read":
			if len(function.Params) == 3 && function.Result == "i32" {
				wrapper.Params = "stream uint32, buffer []byte"
				wrapper.Body = fmt.Sprintf("return %s(stream, bytesPtr(buffer), uint32(len(buffer)))", raw)
				wrapper.Result = " int32"
				wrapper.Stub = "for index := range buffer {\n\t\tbuffer[index] = 0\n\t}\n\treturn 0"
			}
		case "provider_output_write":
			if len(function.Params) == 3 && function.Result == "i32" {
				wrapper.Params = "stream uint32, data []byte"
				wrapper.Body = fmt.Sprintf("return %s(stream, bytesPtr(data), uint32(len(data)))", raw)
				wrapper.Result = " int32"
				wrapper.Stub = "return int32(len(data))"
			}
		}
		wrapper.Doc = fmt.Sprintf("// %s is the generated wrapper for %s.%s.",
			wrapper.Name, host.Name, function.Name)
		wrappers = append(wrappers, wrapper)
	}
	return wrappers
}

// tinyGoScalarParams renders exact IDL scalar parameters and the matching
// argument list, casting defined enum and handle types to their wire base.
func tinyGoScalarParams(d *Definition, params []Param) (string, string) {
	if len(params) == 0 {
		return "", ""
	}
	declarations := make([]string, 0, len(params))
	args := make([]string, 0, len(params))
	for _, param := range params {
		name := tinyGoLocal(param.Name)
		declarations = append(declarations, name+" "+tinyGoTypeName(param.Type))
		args = append(args, tinyGoArg(d, param.Type, name))
	}
	return strings.Join(declarations, ", "), strings.Join(args, ", ")
}

// tinyGoArg names one argument for a raw wasm import call.
func tinyGoArg(d *Definition, typ, name string) string {
	switch typ {
	case "i32", "u32", "i64", "u64":
		return name
	}
	for _, enum := range d.Enums {
		if enum.Name == typ {
			return tinyGoTypeName(enum.Base) + "(" + name + ")"
		}
	}
	for _, handle := range d.Handles {
		if handle.Name == typ {
			return tinyGoTypeName(handle.Base) + "(" + name + ")"
		}
	}
	return name
}

// tinyGoTypeName maps an IDL type to its Go spelling. Enum and handle names
// keep their generated Go type name.
func tinyGoTypeName(typ string) string {
	switch typ {
	case "i32":
		return "int32"
	case "u32":
		return "uint32"
	case "i64":
		return "int64"
	case "u64":
		return "uint64"
	}
	return typ
}

// tinyGoWireTypeName maps an IDL type to the integer type a wasm import
// carries.
func tinyGoWireTypeName(d *Definition, typ string) string {
	switch typ {
	case "i32", "u32", "i64", "u64":
		return tinyGoTypeName(typ)
	}
	for _, enum := range d.Enums {
		if enum.Name == typ {
			return tinyGoTypeName(enum.Base)
		}
	}
	for _, handle := range d.Handles {
		if handle.Name == typ {
			return tinyGoTypeName(handle.Base)
		}
	}
	return typ
}

func tinyGoWireParams(d *Definition, params []Param) string {
	if len(params) == 0 {
		return ""
	}
	parts := make([]string, 0, len(params))
	for _, param := range params {
		parts = append(parts, tinyGoLocal(param.Name)+" "+tinyGoWireTypeName(d, param.Type))
	}
	return strings.Join(parts, ", ")
}

func tinyGoWireResult(d *Definition, result string) string {
	if result == "" {
		return ""
	}
	return " " + tinyGoWireTypeName(d, result)
}

// tinyGoLocal turns an IDL parameter name into a lowerCamel Go local.
func tinyGoLocal(name string) string {
	camel := goCamel(name)
	if camel == "" {
		return camel
	}
	return strings.ToLower(camel[:1]) + camel[1:]
}

// gofmtOrRaw returns gofmt-formatted generated Go, or the raw source when it
// does not parse (the generator bug then shows up as a normal build failure).
func gofmtOrRaw(source string) []byte {
	if formatted, err := format.Source([]byte(source)); err == nil {
		return formatted
	}
	return []byte(source)
}
