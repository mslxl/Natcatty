// Committed generated language-binding paths, relative to the module root.
//
// The C header and the TinyGo package are the canonical SDK outputs. The
// hello-command samples carry checked-in copies so a sample directory is
// self-contained: a writer can copy it anywhere, and the CLI build/dev path
// never depends on include paths outside the plugin directory. LanguageOutputs
// keeps those copies byte-identical to the canonical files.
const (
	CHeaderPath = "sdk/c/natcatty_v1.h"
	CSourcePath = "sdk/c/natcatty_v1.c"

	TinyGoConstantsPath = "sdk/tinygo/abi_v1.go"
	TinyGoHostPath      = "sdk/tinygo/host_tinygo.go"
	TinyGoStubPath      = "sdk/tinygo/host_stub.go"

	helloCommandCHeaderPath = "sdk/samples/hello-command-c/natcatty_v1.h"
	helloCommandCSourcePath = "sdk/samples/hello-command-c/natcatty_v1.c"

	helloCommandTinyGoConstantsPath = "sdk/samples/hello-command-tinygo/bindings/abi_v1.go"
	helloCommandTinyGoHostPath      = "sdk/samples/hello-command-tinygo/bindings/host_tinygo.go"
	helloCommandTinyGoStubPath      = "sdk/samples/hello-command-tinygo/bindings/host_stub.go"

	helloCommandZigHeaderPath = "sdk/samples/hello-command-zig/natcatty_v1.h"
	helloCommandZigSourcePath = "sdk/samples/hello-command-zig/natcatty_v1.c"
)

// GeneratedFile is one committed generator output.
type GeneratedFile struct {
	Path    string
	Content []byte
}

// LanguageOutputs returns the generated C bindings, the generated TinyGo
// package, and the checked-in sample copies of both. Zig consumes the C
// header and C source, so it adds no third wire definition.
func (d *Definition) LanguageOutputs() []GeneratedFile {
	cHeader := d.GenerateCHeader()
	cSource := d.GenerateCSource()
	tinyGoConstants := d.GenerateTinyGoConstants()
	tinyGoHost := d.GenerateTinyGoHost()
	tinyGoStub := d.GenerateTinyGoStub()
	return []GeneratedFile{
		{Path: CHeaderPath, Content: cHeader},
		{Path: CSourcePath, Content: cSource},
		{Path: TinyGoConstantsPath, Content: tinyGoConstants},
		{Path: TinyGoHostPath, Content: tinyGoHost},
		{Path: TinyGoStubPath, Content: tinyGoStub},

		{Path: helloCommandCHeaderPath, Content: cHeader},
		{Path: helloCommandCSourcePath, Content: cSource},
		{Path: helloCommandTinyGoConstantsPath, Content: tinyGoConstants},
		{Path: helloCommandTinyGoHostPath, Content: tinyGoHost},
		{Path: helloCommandTinyGoStubPath, Content: tinyGoStub},
		{Path: helloCommandZigHeaderPath, Content: cHeader},
		{Path: helloCommandZigSourcePath, Content: cSource},
	}
}

// GenerateCHeader renders the C bindings for the IDL. The header is a
// single-header library: declarations and ABI constants are always visible,
// and the generated calls live behind NATCATTY_IMPLEMENTATION so Zig's
// @cImport sees only plain declarations and constants.
func (d *Definition) GenerateCHeader() []byte {
	var out strings.Builder
	out.WriteString("/* Code generated by sdk/idl/gen from sdk/idl/natcatty_v1.idl; DO NOT EDIT. */\n\n")
	out.WriteString("#ifndef NATCATTY_V1_GENERATED_H\n#define NATCATTY_V1_GENERATED_H\n\n")
	out.WriteString("/*\n")
	out.WriteString(" * Natcatty plugin ABI v" + fmt.Sprintf("%d", d.ABI) + " C bindings.\n")
	out.WriteString(" *\n")
	out.WriteString(" * The ABI is wasm32: a pointer is 32 bits, int is 32 bits, and long long\n")
	out.WriteString(" * is 64 bits. The header is freestanding so clang and Zig's @cImport can\n")
	out.WriteString(" * read it without a libc. Compile natcatty_v1.c with the plugin or define\n")
	out.WriteString(" * NATCATTY_IMPLEMENTATION before including this header.\n")
	out.WriteString(" */\n\n")
	out.WriteString("typedef signed int natcatty_i32;\n")
	out.WriteString("typedef unsigned int natcatty_u32;\n")
	out.WriteString("typedef signed long long natcatty_i64;\n")
	out.WriteString("typedef unsigned long long natcatty_u64;\n\n")
	fmt.Fprintf(&out, "#define NATCATTY_IDL_NAME %q\n", d.Name)
	fmt.Fprintf(&out, "#define NATCATTY_IDL_VERSION %q\n", d.Version)
	fmt.Fprintf(&out, "#define NATCATTY_ABI_VERSION %d\n", d.ABI)
	fmt.Fprintf(&out, "#define NATCATTY_HOST_MODULE %q\n\n", d.HostModule().Name)
	out.WriteString("/* Pointer to a guest memory offset. Callers pass addresses of static or\n")
	out.WriteString(" * heap buffers; the host never retains them past the call. */\n")
	out.WriteString("#define NATCATTY_PTR(value) ((natcatty_u32)(unsigned long)(value))\n\n")
	out.WriteString("#if defined(__wasm__)\n")
	out.WriteString("#define NATCATTY_IMPORT(module, name) __attribute__((import_module(module), import_name(name)))\n")
	out.WriteString("#define NATCATTY_EXPORT(name) __attribute__((visibility(\"default\"), export_name(name)))\n")
	out.WriteString("#else\n")
	out.WriteString("#define NATCATTY_IMPORT(module, name)\n")
	out.WriteString("#define NATCATTY_EXPORT(name)\n")
	out.WriteString("#endif\n\n")

	for _, enum := range d.Enums {
		out.WriteString("/* Values are part of the wire contract. */\n")
		if enum.Base == "i64" {
			fmt.Fprintf(&out, "typedef natcatty_i64 natcatty_%s;\n", snakeCase(enum.Name))
			for _, value := range enum.Values {
				fmt.Fprintf(&out, "#define %s ((natcatty_%s)%d)\n",
					cEnumValue(enum, value.Name), snakeCase(enum.Name), value.Value)
			}
			out.WriteString("\n")
			continue
		}
		fmt.Fprintf(&out, "typedef enum natcatty_%s {\n", snakeCase(enum.Name))
		for _, value := range enum.Values {
			fmt.Fprintf(&out, "  %s = %d,\n", cEnumValue(enum, value.Name), value.Value)
		}
		fmt.Fprintf(&out, "} natcatty_%s;\n\n", snakeCase(enum.Name))
	}

	for _, record := range d.Records {
		fmt.Fprintf(&out, "/* Fixed field-by-field record %s. */\n", record.Name)
		fmt.Fprintf(&out, "typedef struct natcatty_%s {\n", snakeCase(record.Name))
		for _, field := range record.Fields {
			fmt.Fprintf(&out, "  %s %s;\n", cType(d, field.Type), snakeCase(field.Name))
		}
		fmt.Fprintf(&out, "} natcatty_%s;\n\n", snakeCase(record.Name))
	}

	for _, handle := range d.Handles {
		fmt.Fprintf(&out, "/* Opaque generation-tagged %s; the low 32 bits are the slot. */\n", handle.Name)
		fmt.Fprintf(&out, "typedef natcatty_u64 natcatty_%s;\n\n", snakeCase(handle.Name))
	}

	host := d.HostModule()
	out.WriteString("/* Host imports from " + host.Name + ". The generated implementation in\n")
	out.WriteString(" * natcatty_v1.c binds each call to the wasm import table. */\n")
	for _, function := range host.Functions {
		fmt.Fprintf(&out, "%s natcatty_host_%s(%s);\n",
			cReturnType(d, function.Result), snakeCase(function.Name), cParams(d, function.Params))
	}
	out.WriteString("\n")

	for _, service := range d.Services {
		upper := strings.ToUpper(snakeCase(service.Name))
		fmt.Fprintf(&out, "/* Host service %s. */\n", service.Name)
		fmt.Fprintf(&out, "#define NATCATTY_SVC_%s_NAME %q\n", upper, service.Name)
		fmt.Fprintf(&out, "#define NATCATTY_SVC_%s_MODULE %q\n", upper, service.Module())
		for _, method := range service.Methods {
			fmt.Fprintf(&out, "#define NATCATTY_SVC_%s_METHOD_%s %du\n",
				upper, strings.ToUpper(snakeCase(method.Name)), method.ID)
		}
		fmt.Fprintf(&out, "natcatty_i32 natcatty_svc_%s_call(natcatty_u32 method_id, natcatty_u32 req_ptr, natcatty_u32 req_len, natcatty_u32 resp_ptr, natcatty_u32 resp_cap);\n",
			snakeCase(service.Name))
		fmt.Fprintf(&out, "natcatty_i32 natcatty_svc_%s_invoke(natcatty_u32 method_id, const void *request, natcatty_u32 request_len, void *response, natcatty_u32 response_capacity);\n\n",
			snakeCase(service.Name))
	}

	guest := d.GuestModule()
	out.WriteString("/* Guest export wire names and export attributes. */\n")
	for _, export := range guest.Exports {
		upper := strings.ToUpper(snakeCase(export.Name))
		fmt.Fprintf(&out, "#define NATCATTY_WIRE_%s %q\n", upper, export.Wire)
	}
	out.WriteString("\n#if defined(__wasm__)\n")
	for _, export := range guest.Exports {
		upper := strings.ToUpper(snakeCase(export.Name))
		fmt.Fprintf(&out, "#define NATCATTY_EXPORT_%s __attribute__((visibility(\"default\"), export_name(%q)))\n",
			upper, export.Wire)
	}
	out.WriteString("#else\n")
	for _, export := range guest.Exports {
		upper := strings.ToUpper(snakeCase(export.Name))
		fmt.Fprintf(&out, "#define NATCATTY_EXPORT_%s\n", upper)
	}
	out.WriteString("#endif\n\n")

	out.WriteString("/* Checks the host abi_version against NATCATTY_ABI_VERSION. On a mismatch\n")
	out.WriteString(" * it logs one error line and returns -1; on success it returns 0. Call it\n")
	out.WriteString(" * from natcatty_init and fail init when it does not return 0. */\n")
	out.WriteString("natcatty_i32 natcatty_guest_init(void);\n\n")

	out.WriteString("#ifdef NATCATTY_IMPLEMENTATION\n\n")
	out.WriteString("/* Raw wasm imports. Their wire module and field names come from the IDL. */\n")
	for _, function := range host.Functions {
		fmt.Fprintf(&out, "NATCATTY_IMPORT(%q, %q) %s natcatty_raw_host_%s(%s);\n",
			host.Name, function.Name, cWireReturnType(d, function.Result),
			snakeCase(function.Name), cWireParams(d, function.Params))
	}
	out.WriteString("\n")
	for _, function := range host.Functions {
		args := cArgList(function.Params)
		call := fmt.Sprintf("natcatty_raw_host_%s(%s)", snakeCase(function.Name), args)
		body := call + ";\n"
		if function.Result != "" {
			body = "return " + call + ";\n"
		}
		fmt.Fprintf(&out, "%s natcatty_host_%s(%s) {\n  %s}\n",
			cReturnType(d, function.Result), snakeCase(function.Name),
			cParams(d, function.Params), body)
	}
	out.WriteString("\n")

	for _, service := range d.Services {
		fmt.Fprintf(&out, "NATCATTY_IMPORT(%q, %q) natcatty_i32 natcatty_raw_svc_%s_call(natcatty_u32 method_id, natcatty_u32 req_ptr, natcatty_u32 req_len, natcatty_u32 resp_ptr, natcatty_u32 resp_cap);\n",
			service.Module(), serviceCallFunction, snakeCase(service.Name))
	}
	out.WriteString("\n")
	for _, service := range d.Services {
		name := snakeCase(service.Name)
		fmt.Fprintf(&out, "natcatty_i32 natcatty_svc_%s_call(natcatty_u32 method_id, natcatty_u32 req_ptr, natcatty_u32 req_len, natcatty_u32 resp_ptr, natcatty_u32 resp_cap) {\n", name)
		fmt.Fprintf(&out, "  return natcatty_raw_svc_%s_call(method_id, req_ptr, req_len, resp_ptr, resp_cap);\n}\n", name)
		fmt.Fprintf(&out, "natcatty_i32 natcatty_svc_%s_invoke(natcatty_u32 method_id, const void *request, natcatty_u32 request_len, void *response, natcatty_u32 response_capacity) {\n", name)
		fmt.Fprintf(&out, "  return natcatty_svc_%s_call(method_id, NATCATTY_PTR(request), request_len, NATCATTY_PTR(response), response_capacity);\n}\n\n", name)
	}

	fmt.Fprintf(&out, "static const char natcatty_abi_mismatch_message[] =\n")
	fmt.Fprintf(&out, "    %q;\n\n", fmt.Sprintf("plugin ABI mismatch: generated C bindings speak ABI %d\n", d.ABI))
	out.WriteString("natcatty_i32 natcatty_guest_init(void) {\n")
	out.WriteString("  if (natcatty_host_abi_version() != NATCATTY_ABI_VERSION) {\n")
	out.WriteString("    natcatty_host_log(NATCATTY_LOG_LEVEL_ERROR,\n")
	out.WriteString("        NATCATTY_PTR(natcatty_abi_mismatch_message),\n")
	out.WriteString("        (natcatty_u32)(sizeof(natcatty_abi_mismatch_message) - 1));\n")
	out.WriteString("    return -1;\n")
	out.WriteString("  }\n")
	out.WriteString("  return 0;\n")
	out.WriteString("}\n\n")
	out.WriteString("#endif /* NATCATTY_IMPLEMENTATION */\n\n")
	out.WriteString("#endif /* NATCATTY_V1_GENERATED_H */\n")
	return []byte(out.String())
}

// GenerateCSource renders the one translation unit that implements the header's
// imported calls and the generated ABI check.
func (d *Definition) GenerateCSource() []byte {
	var out strings.Builder
	out.WriteString("/* Code generated by sdk/idl/gen from sdk/idl/natcatty_v1.idl; DO NOT EDIT. */\n\n")
	out.WriteString("#define NATCATTY_IMPLEMENTATION\n")
	out.WriteString("#include \"natcatty_v1.h\"\n")
	return []byte(out.String())
}

// cType maps an IDL type to its public C spelling.
func cType(d *Definition, typ string) string {
	switch typ {
	case "i32", "u32", "i64", "u64":
		return "natcatty_" + typ
	}
	for _, enum := range d.Enums {
		if enum.Name == typ {
			return "natcatty_" + snakeCase(enum.Name)
		}
	}
	for _, record := range d.Records {
		if record.Name == typ {
			return "natcatty_" + snakeCase(record.Name)
		}
	}
	for _, handle := range d.Handles {
		if handle.Name == typ {
			return "natcatty_" + snakeCase(handle.Name)
		}
	}
	return typ
}

// cWireType maps an IDL type to the integer type the WebAssembly call
// actually carries. Enums and handles lower to their declared base.
func cWireType(d *Definition, typ string) string {
	switch typ {
	case "i32", "u32", "i64", "u64":
		return "natcatty_" + typ
	}
	for _, enum := range d.Enums {
		if enum.Name == typ {
			return "natcatty_" + enum.Base
		}
	}
	for _, handle := range d.Handles {
		if handle.Name == typ {
			return "natcatty_" + handle.Base
		}
	}
	return typ
}

func cReturnType(d *Definition, result string) string {
	if result == "" {
		return "void"
	}
	return cType(d, result)
}

func cWireReturnType(d *Definition, result string) string {
	if result == "" {
		return "void"
	}
	return cWireType(d, result)
}

func cParams(d *Definition, params []Param) string {
	if len(params) == 0 {
		return "void"
	}
	parts := make([]string, 0, len(params))
	for _, param := range params {
		parts = append(parts, cType(d, param.Type)+" "+snakeCase(param.Name))
	}
	return strings.Join(parts, ", ")
}

func cWireParams(d *Definition, params []Param) string {
	if len(params) == 0 {
		return "void"
	}
	parts := make([]string, 0, len(params))
	for _, param := range params {
		parts = append(parts, cWireType(d, param.Type)+" "+snakeCase(param.Name))
	}
	return strings.Join(parts, ", ")
}

func cArgList(params []Param) string {
	parts := make([]string, 0, len(params))
	for _, param := range params {
		parts = append(parts, snakeCase(param.Name))
	}
	return strings.Join(parts, ", ")
}

func cEnumValue(enum Enum, value string) string {
	return "NATCATTY_" + strings.ToUpper(snakeCase(enum.Name)) + "_" + strings.ToUpper(snakeCase(value))
}

// snakeCase converts IDL CamelCase names to lower_snake_case. It keeps
// acronym runs together (PropID -> prop_id, UIOpKind -> ui_op_kind).
func snakeCase(name string) string {
	runes := []rune(name)
	var out strings.Builder
	for i, r := range runes {
		switch {
		case r >= 'A' && r <= 'Z':
			prevLower := i > 0 && runes[i-1] >= 'a' && runes[i-1] <= 'z'
			prevDigit := i > 0 && runes[i-1] >= '0' && runes[i-1] <= '9'
			nextLower := i+1 < len(runes) && runes[i+1] >= 'a' && runes[i+1] <= 'z'
			if i > 0 && (prevLower || prevDigit || (nextLower && runes[i-1] >= 'A' && runes[i-1] <= 'Z')) {
				out.WriteByte('_')
			}
			out.WriteRune(r - 'A' + 'a')
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			out.WriteRune(r)
		default:
			out.WriteByte('_')
		}
	}
	return out.String()
}
